BRANCH_ORDER = ("tactics", "diplomacy", "keeper")


def capacity(style: str) -> int:
    return sum(len(v) for v in POOL[style].values())


def allocate(style: str, count: int, taken: set[str] | None = None) -> list[tuple[str, str]]:
    """Раздаёт `count` уникальных кличек, равномерно распределяя по веткам.

    Возвращает список (кличка, ветка). `taken` — уже занятые в классе клички.
    """
    if style not in POOL:
        raise ValueError(f"Неизвестный стиль кличек: {style!r}")
    used = set(taken or ())
    free: dict[str, list[str]] = {
        branch: [n for n in names if n not in used]
        for branch, names in POOL[style].items()
    }
    for names in free.values():
        secrets.SystemRandom().shuffle(names)

    if sum(len(v) for v in free.values()) < count:
        raise ValueError(
            f"В стиле «{STYLE_TITLES[style]}» осталось "
            f"{sum(len(v) for v in free.values())} свободных кличек, нужно {count}"
        )

    out: list[tuple[str, str]] = []
    i = 0
    while len(out) < count:
        branch = BRANCH_ORDER[i % len(BRANCH_ORDER)]
        i += 1
        if free[branch]:
            out.append((free[branch].pop(), branch))
    return out
