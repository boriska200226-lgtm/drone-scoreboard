#!/bin/sh
# Миграции — до старта сервера: схема должна существовать раньше первого запроса.
set -e
python -m app.migrate

# ВНИМАНИЕ: комнаты WebSocket живут в памяти процесса, а ночной пересчёт Брони —
# в его планировщике. Поэтому по умолчанию работает ОДИН воркер: при
# WEB_CONCURRENCY>1 свисток дойдёт только до части класса, а Броня пересчитается
# столько раз, сколько воркеров. Для нескольких воркеров нужен общий брокер
# (Redis pub/sub) — см. README, раздел «Масштабирование».
exec uvicorn app.main:app \
    --host 0.0.0.0 \
    --port 8000 \
    --proxy-headers \
    --forwarded-allow-ips '*' \
    --ws websockets \
    --workers "${WEB_CONCURRENCY:-1}"
